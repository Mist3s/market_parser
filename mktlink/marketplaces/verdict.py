"""Вердикты и статусы продавца.

Разделение классов здесь несёт деньги и корректность, а не аккуратность:

* ``SILENT_EMPTY`` штрафует прокси. Это нормальная форма антибот-блока с
  датацентрового адреса: HTTP 200, валидно выглядящая страница, ноль товаров.
* ``SCHEMA_DRIFT`` прокси **не касается вообще**. Маркетплейс переименовал
  ключ — виноват наш парсер, и списывать за это адрес значит покупать новый
  каждый раз, когда Ozon выкатывает релиз.
* ``NOT_FOUND`` требует положительного доказательства плюс второго
  независимого подтверждения. Вывести его из отсутствия данных нельзя:
  молчаливый ноль — это блок, а не отсутствие товара.
* ``BUDGET_EXHAUSTED`` — наша вина, не прокси. Скорер его игнорирует.
"""

from __future__ import annotations

from enum import StrEnum


class Verdict(StrEnum):
    """Исход одной ступени лестницы."""

    OK = "ok"
    #: Имя есть, продавца нет. Честный частичный ответ, а не отказ.
    PARTIAL = "partial"
    #: Блок офферов дорисовывается на клиенте — SSR его не содержит.
    CLIENT_RENDERED = "client_rendered"
    #: 200 и пусто. Форма блока, а не форма отсутствия.
    SILENT_EMPTY = "silent_empty"
    #: Идентичность страницы есть, кандидаты есть, а якоря в них нет.
    SCHEMA_DRIFT = "schema_drift"
    #: Положительный маркер отсутствия. Требует второго подтверждения.
    NOT_FOUND = "not_found"
    CAPTCHA = "captcha"
    HTTP_429 = "http_429"
    UPSTREAM_ERROR = "upstream_error"
    #: Наш бюджет кончился. К прокси отношения не имеет.
    BUDGET_EXHAUSTED = "budget_exhausted"
    #: Челлендж на прямом, беспрокси-егрессе раскрутки.
    UNWIND_CHALLENGED = "unwind_challenged"


class SellerStatus(StrEnum):
    """Почему продавец такой, какой есть. Всегда присутствует в ответе."""

    #: Найден по якорному пути.
    RESOLVED = "resolved"
    #: Продавец — сам маркетплейс, и это факт, а не наша неудача.
    FIRST_PARTY = "first_party"
    #: У карточки офферов нет вовсе. Правильный ответ, а не отказ.
    NO_OFFERS = "no_offers"
    #: Оффер, на который указывала ссылка, исчез. Подставлять другого
    #: продавца запрещено: это была бы тихая неправда.
    OFFER_GONE = "offer_gone"
    #: Разметка изменилась — путь не найден. Payload семплируется.
    UNKNOWN_LAYOUT = "unknown_layout"
    #: Блок продавца рисуется на клиенте, SSR его не содержит.
    DEFERRED_RENDER = "deferred_render"
    #: Бюджет кончился до обогащающей ступени.
    OUT_OF_BUDGET = "out_of_budget"


#: Вердикты, которые СЧИТАЮТСЯ уликой против прокси. Всё остальное — нет.
#: Список положительный, а не отрицательный, намеренно: новый вердикт по
#: умолчанию прокси не штрафует, и это безопасная сторона ошибки.
CHARGES_PROXY: frozenset[Verdict] = frozenset(
    {
        Verdict.SILENT_EMPTY,
        Verdict.CAPTCHA,
        Verdict.HTTP_429,
        Verdict.UPSTREAM_ERROR,
    }
)

#: Вердикты, при которых ответ клиенту содержателен.
USABLE: frozenset[Verdict] = frozenset({Verdict.OK, Verdict.PARTIAL})


def charges_proxy(verdict: Verdict, *, egress: str) -> bool:
    """Считать ли наблюдение уликой против прокси.

    Двойное условие, и второе не менее важно первого: наблюдение, сделанное
    НЕ через прокси, уликой против прокси быть не может. Раскрутка редиректов
    идёт прямым егрессом, поэтому увиденный в ней челлендж не имеет права
    списать единственный адрес и запустить закупку нового.
    """
    return egress == "proxy" and verdict in CHARGES_PROXY
