"""Единственный дом для всех таймингов и порогов.

Два класса констант, и различение между ними несущее (§3.2 спецификации):

* **Класс I — физика.** DNS, TCP, накладные ASGI. От ручки `RESPONSE_BUDGET_MS`
  не зависят, потому что это свойства сети и рантайма, а не нашего контракта.
* **Класс II — производные от ручки.** Живут в :mod:`mktlink.budget`, потому что
  все до одной выводятся функцией ``derive(B, mp, hops)``.

CI-гейт: литерала ``timeout=<число>`` нет нигде в пакете, кроме этого модуля.
"""

from __future__ import annotations

from typing import Final

MARKETPLACES: Final[tuple[str, ...]] = ("ozon", "wb", "ym")

# --- Класс I: физика ---------------------------------------------------------

DNS_MS: Final[int] = 150
CONNECT_MS: Final[int] = 250
HOP_HEADERS_MS: Final[int] = 150
#: Стоимость одного редирект-хопа. Заголовки читаются за 150 мс законно:
#: ``follow_redirects=False`` + ``Range: bytes=0-0`` — нужны только статусная
#: строка и ``Location``, тела нет.
HOP_MS: Final[int] = DNS_MS + CONNECT_MS + HOP_HEADERS_MS  # 550
REDIRECT_HOPS_MAX: Final[int] = 3
REDIRECT_CAP_MS: Final[int] = REDIRECT_HOPS_MAX * HOP_MS  # 1650

#: Шаги 1,2,3,4,6,7 пути запроса: 20+15+10+15+15+10.
FIXED_PRE_MS: Final[int] = 85
SER_MS: Final[int] = 25
#: ASGI write 45 + jitter 50.
TAIL_MS: Final[int] = 95
#: loop-lag p99 (~60) × 2. Один процесс, ρ ≈ 8 %.
SAFETY_MS: Final[int] = 120

#: Разный по маркетплейсам не из придирчивости: Ozon и WB отдают JSON, а
#: Я.Маркет — HTML-PDP в сотни KiB, где полный DOM-парс стоит сотни мс. Отсюда
#: regex-first в :mod:`mktlink.extract.jsonscan`.
PARSE_MS: Final[dict[str, int]] = {"ozon": 60, "wb": 60, "ym": 200}

#: Минимальный интервал между исходящими на паре (маркетплейс, прокси).
#:
#: Три числа с разной доказательной базой, и это надо помнить:
#:
#: * ``wb: 2000`` — наблюдение из удалённого скрейпера (``841dac3``,
#:   ``market_parser/stores/wildberries.py:57``), и оно ОПТИМИСТИЧНО.
#:   ЗАМЕР 2026-09-03: пять запросов через датацентровый IPv4 proxy6,
#:   разнесённых на 2 с, дали ``HTTP 429``. Скрейпер работал с другого IP,
#:   поэтому его значение сюда не переносится напрямую. Первый кандидат на
#:   пересмотр по Phase 0.
#: * ``ozon: 5000`` — ГИПОТЕЗА, причём консервативная против самого
#:   репозитория: ``ozon.py:79`` ставит между страницами composer-API
#:   ``wait_for_timeout(700)``, и это работает. 5000 — наша осторожность,
#:   а не наблюдение. Самый дорогой тюнабл в системе.
#: * ``ym: 600`` — ВЫВЕДЕНО, не наблюдение: наибольшее значение, при котором
#:   гард самофинансируется, то есть не превышает пола самой короткой ступени
#:   лестницы (``Y5``, floor 600). Прежние 700 этим свойством не обладали.
MIN_INTERVAL_MS: Final[dict[str, int]] = {"ozon": 5000, "wb": 2000, "ym": 600}

KEEPALIVE_IDLE_S: Final[int] = 300

#: Балкхед на одновременные запросы.
#:
#: **Единственная константа этого класса, которая по существу зависит от
#: ручки, и это стоит признать вслух.** Обоснование — очередь M/G/∞ с
#: загрузкой ``L = λ·B``. При 3 запросах в минуту и бюджете 15 с было
#: L = 0.75 и P(N ≥ 5) = 0.11 %. При бюджете 30 с L = 1.5, и та же
#: вероятность становится 1.86 % — рост быстрых отказов ``503`` в
#: семнадцать раз при неизменном потоке.
#:
#: Поэтому балкхед поднят до 6: при L = 1.5 это даёт P(N ≥ 7) = 0.11 %,
#: то есть ровно ту вероятность отказа, что была до удвоения бюджета.
#: Цена — до шести одновременных запросов в полёте вместо четырёх; при
#: 2–3 запросах в минуту это память, а не нагрузка.
GLOBAL_SEMAPHORE: Final[int] = 6

#: Минтинг никогда не идёт по пути запроса, поэтому его потолок не связан с
#: ручкой и заведомо больше её максимума.
#:
#: Число ЖИВЁТ В ДВУХ ФАЙЛАХ — здесь и в ``mktlink/mint/rpc.py``, где оно
#: работает дефолтом ETA коалесцера. Инвариант «больше максимума ручки»
#: проверялся по ЭТОЙ копии, а использовалась та: подняв одну, легко было
#: починить тест и оставить коалесцер обещать 25 с при бюджете 30 с.
#: Поэтому rpc теперь импортирует значение отсюда, а не объявляет своё.
MINT_HARD_CAP_MS: Final[int] = 35_000

# --- Ручка и её границы ------------------------------------------------------

RESPONSE_BUDGET_MIN_MS: Final[int] = 5_000

#: Потолок поднят с 15 до 30 секунд по замеру, а не по желанию.
#:
#: Карточка Ozon через скрейпинг-API отдаётся 9 098–25 633 мс (одиннадцать
#: наблюдений 2026-09-03). При потолке 15 с ступень получала 13.5 с и
#: укладывалась примерно в половине случаев; остальное уходило в ``202``.
#: Тридцать секунд покрывают самое медленное наблюдение с запасом на
#: сокращение ссылки (см. ``SHORTEN_CAP_MS``).
#:
#: Что это стоит, названо прямо: удвоение времени удержания слота удваивает
#: загрузку балкхеда, поэтому вместе с потолком поднят ``GLOBAL_SEMAPHORE``.
RESPONSE_BUDGET_MAX_MS: Final[int] = 30_000
RESPONSE_BUDGET_DEFAULT_MS: Final[int] = 30_000

#: Потолок эндпоинта раскрутки. Своё число, НЕ производное от ручки ответа.
#:
#: Раскрутка — это до трёх редиректов по ``HOP_MS`` плюс валидация: три с
#: половиной секунды с запасом. Выводить её из потолка карточки значило бы
#: разрешить тридцать секунд гоняться за редиректами только потому, что
#: столько нужно карточке Ozon. Это разные работы с разной физикой.
RESOLVE_BUDGET_MS: Final[int] = 4_000

#: Арифметический пол: ниже него лестницы не существует ни для одного
#: маркетплейса. = 485 + REDIRECT_CAP_MS + STAGE_RESERVE["ym"] + floor(Y1)
#: = 485 + 1650 + 440 + 1100. Достижим только через ``max_wait_ms``.
BUDGET_FLOOR_MS: Final[int] = 3_675

# --- Retry-After -------------------------------------------------------------

#: Ждём полный минтинг jar (пол 7230, p50 8800, p95 11420) плюс публикацию.
RETRY_AFTER_MINT_S: Final[int] = 25
#: jar тёплый — нужен только слот или второй прокси.
RETRY_AFTER_FETCH_S: Final[int] = 3
#: 503 CAPACITY_EXHAUSTED: ждём освобождения ёмкости, а не конкретной работы.
RETRY_AFTER_SHED_S: Final[int] = 5

#: Подсказка клиенту: его таймаут обязан быть выше нашего потолка.
CLIENT_TIMEOUT_MARGIN_MS: Final[int] = 500

# --- Спейсинг и канарейка ----------------------------------------------------

#: Одна проба на маркетплейс в час. При клиентских 60 req/ч на маркетплейс это
#: λ = 61 req/ч (средний зазор 59.0 с) и суммарный егресс 183 req/ч = 3.05/мин,
#: то есть на 1.7 % выше заявленного клиентом потолка — это названо честно,
#: а не спрятано. Прежние 1/180 с давали 4 req/мин, треть сверху.
CANARY_PERIOD_S: Final[int] = 3600
CANARY_MAX_AGE_S: Final[int] = 3900
